function todayUtc(): Date {
  const now = new Date();
  return new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate()));
}

function addDays(d: Date, n: number): Date {
  return new Date(d.getTime() + n * 86_400_000);
}

function isoDay(d: Date): string {
  return d.toISOString().slice(0, 10);
}

function daysSequence(from: Date, count: number): string[] {
  return Array.from({ length: count }, (_, i) => isoDay(addDays(from, i)));
}

function dateAtUtc(day: string, hour: number, minute = 0, second = 0): Date {
  return new Date(`${day}T${String(hour).padStart(2, '0')}:${String(minute).padStart(2, '0')}:${String(second).padStart(2, '0')}Z`);
}

function toNumeric(value: number | null): string | null {
  return value === null ? null : String(value);
}

