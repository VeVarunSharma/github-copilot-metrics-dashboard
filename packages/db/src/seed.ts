function splitByWeightMap(total: number, weights: ReadonlyArray<readonly [string, number]>): Map<string, number> {
  const out = new Map<string, number>();
  let remaining = Math.max(0, Math.round(total));
  for (let i = 0; i < weights.length; i += 1) {
    const item = weights[i]!;
    const share =
      i === weights.length - 1 ?
        remaining
      : Math.min(remaining, Math.max(0, Math.round(total * item[1])));
    out.set(item[0], share);
    remaining -= share;
  }
  return out;
}

function buildFeatureInteractionShares(profile: DailyProfile): Map<string, number> {
  const out = splitByWeightMap(profile.totalChatInteractions, CHAT_INTERACTION_WEIGHTS);
  out.set('agent', profile.totalAgentInteractions);
  return out;
}

function userConsumptionShares(count: number): number[] {
  const raw = Array.from({ length: count }, (_, i) => 1 / (i + 1) ** 1.25);
  const total = raw.reduce((sum, value) => sum + value, 0);
  return raw.map((value) => value / total);
}

function teamForUserIndex(index: number, teamIds: readonly bigint[]): bigint {
  return teamIds[index % teamIds.length] ?? 940_000_001n;
}

