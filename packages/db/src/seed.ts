interface DailyProfile {
  day: string;
  dayIndex: number;
  isWeekend: boolean;
  activeUsers: number;
  totalCompletions: number;
  totalAccepted: number;
  totalLocAdded: number;
  totalLocDeleted: number;
  totalLocSuggestedAdd: number;
  totalLocSuggestedDelete: number;
  totalChatInteractions: number;
  totalAgentInteractions: number;
  prsCreated: number;
  prsCreatedByCopilot: number;
  prsMerged: number;
  prsMergedByCopilot: number;
  prsReviewed: number;
  prsReviewedByCopilot: number;
}

function generateDailyProfile(day: string, dayIndex: number, totalDays: number, rng: () => number): DailyProfile {
  const date = new Date(`${day}T00:00:00Z`);
  const dow = date.getUTCDay();
  const isWeekend = dow === 0 || dow === 6;
  const weekdayMultiplier = isWeekend ? 0.2 : 1;

  // Adoption growth curve: 5 → 35 users over the window.
  const growth = 5 + Math.round((totalDays === 1 ? 1 : dayIndex / (totalDays - 1)) * 30);
  const activeUsers = Math.max(1, jitter(rng, growth, 3));
  const baseCompletionsPerUser = jitter(rng, 35, 12) * weekdayMultiplier;
  const baseChatPerUser = jitter(rng, 14, 5) * weekdayMultiplier;
  const baseAgentPerUser = jitter(rng, 3, 1.5) * weekdayMultiplier;

  const totalCompletions = Math.max(isWeekend ? activeUsers * 6 : activeUsers * 20, Math.round(activeUsers * baseCompletionsPerUser));
  const acceptanceRate = 0.45 + rng() * 0.2;
  const totalAccepted = Math.round(totalCompletions * acceptanceRate);
  const locPerAcceptance = 4 + rng() * 6;
  const totalLocAdded = Math.max(isWeekend ? activeUsers * 24 : activeUsers * 60, Math.round(totalAccepted * locPerAcceptance));
  const totalLocDeleted = Math.max(isWeekend ? 6 : 12, Math.round(totalLocAdded * (0.1 + rng() * 0.15)));
  const totalLocSuggestedAdd = Math.max(
    Math.round(totalLocAdded / acceptanceRate),
    Math.round(totalCompletions * locPerAcceptance),
  );
  const totalLocSuggestedDelete = Math.max(
    Math.round(totalLocDeleted / acceptanceRate),
    Math.round(totalLocSuggestedAdd * (0.1 + rng() * 0.15)),
  );
  const totalChatInteractions = Math.max(isWeekend ? 6 : activeUsers * 4, Math.round(activeUsers * baseChatPerUser));
  const rawAgentInteractions = Math.round(activeUsers * baseAgentPerUser);
  const totalAgentInteractions = Math.min(
    Math.max(isWeekend ? 1 : Math.ceil(activeUsers * 0.4), rawAgentInteractions),
    Math.max(1, Math.floor(totalChatInteractions * 0.35)),
  );

  const prsCreated = isWeekend ? jitter(rng, 1, 1) : jitter(rng, 4 + dayIndex / 12, 2);
  const copilotPrShare = 0.35 + rng() * 0.25;
  const prsCreatedByCopilot = Math.round(prsCreated * copilotPrShare);
  const prsMerged = Math.max(0, prsCreated - jitter(rng, 1, 1));
  const prsMergedByCopilot = Math.min(prsMerged, prsCreatedByCopilot);
  const prsReviewed = prsCreated + jitter(rng, 1, 1);
  const prsReviewedByCopilot = Math.round(prsReviewed * (0.4 + rng() * 0.3));

  return {
    day,
    dayIndex,
    isWeekend,
    activeUsers,
    totalCompletions,
    totalAccepted,
    totalLocAdded,
    totalLocDeleted,
    totalLocSuggestedAdd,
    totalLocSuggestedDelete,
    totalChatInteractions,
    totalAgentInteractions,
    prsCreated,
    prsCreatedByCopilot,
    prsMerged,
    prsMergedByCopilot,
    prsReviewed,
    prsReviewedByCopilot,
  };
}

async function seedDemoReleaseFacts(db: Database, repoIds: readonly bigint[]): Promise<void> {
  const rng = mulberry32(20260620);
  const days = daysSequence(addDays(todayUtc(), -DEMO_DAYS + 1), DEMO_DAYS);
  console.log('• demo: seeding release aggregates');

  for (let dayIndex = 0; dayIndex < days.length; dayIndex += 1) {
    const day = days[dayIndex]!;
    const date = new Date(`${day}T00:00:00Z`);
    const isWeekend = date.getUTCDay() === 0 || date.getUTCDay() === 6;
    const releaseCount =
      isWeekend ? (rng() < 0.35 ? 1 : 0) + (rng() < 0.05 ? 1 : 0) : 1 + Math.floor(rng() * 3);

    const byRepo = new Map<bigint, { releaseCount: number; prereleaseCount: number; latestTagAt: Date }>();
    for (let r = 0; r < releaseCount; r += 1) {
      const repoId = repoIds[(dayIndex + r + Math.floor(rng() * repoIds.length)) % repoIds.length]!;
      const isPrerelease = rng() < 0.2;
      const tagAt = dateAtUtc(day, 13 + Math.floor(rng() * 6), Math.floor(rng() * 60));
      const current = byRepo.get(repoId) ?? { releaseCount: 0, prereleaseCount: 0, latestTagAt: tagAt };
      current.releaseCount += 1;
      current.prereleaseCount += isPrerelease ? 1 : 0;
      if (tagAt.getTime() > current.latestTagAt.getTime()) current.latestTagAt = tagAt;
      byRepo.set(repoId, current);
    }

    for (const [repoId, aggregate] of byRepo) {
      const values = {
        orgId: DEMO_ORG_SLUG,
        repoId,
        day,
        releaseCount: aggregate.releaseCount,
        prereleaseCount: aggregate.prereleaseCount,
        latestTagAt: aggregate.latestTagAt,
      };
      await db.insert(factReleaseDaily).values(values).onConflictDoUpdate({
        target: [factReleaseDaily.orgId, factReleaseDaily.repoId, factReleaseDaily.day],
        set: values,
      });
    }
  }
}

async function seedDemoWorkflowRunFacts(db: Database, repoIds: readonly bigint[]): Promise<void> {
  const rng = mulberry32(20260621);
  const days = daysSequence(addDays(todayUtc(), -DEMO_DAYS + 1), DEMO_DAYS);
  console.log('• demo: seeding workflow run aggregates');

  for (let dayIndex = 0; dayIndex < days.length; dayIndex += 1) {
    const day = days[dayIndex]!;
    const isWeekend = new Date(`${day}T00:00:00Z`).getUTCDay() % 6 === 0;
    const growth = 0.75 + (dayIndex / Math.max(1, days.length - 1)) * 0.5;

    for (let repoIndex = 0; repoIndex < repoIds.length; repoIndex += 1) {
      const repoId = repoIds[repoIndex]!;
      const workflowCount = repoIndex === 4 ? 2 : 3;
      for (let workflowOffset = 0; workflowOffset < workflowCount; workflowOffset += 1) {
        const workflowId = BigInt(Number(repoId) * 100 + workflowOffset + 1);
        const baseRuns = repoIndex === 4 ? 2 : 5 + repoIndex;
        const totalRuns = Math.max(1, Math.round(jitter(rng, baseRuns * growth * (isWeekend ? 0.35 : 1), 2)));
        const cancelledCount = rng() < 0.08 ? 1 : 0;
        const completedRuns = Math.max(0, totalRuns - cancelledCount);
        const baselineFailures = Math.floor(completedRuns * (0.025 + rng() * 0.035));
        const scheduledFailure =
          completedRuns >= 2 && (dayIndex + repoIndex + workflowOffset) % 6 === 0 ? 1 : 0;
        const failureCount = Math.min(
          completedRuns,
          baselineFailures + scheduledFailure + (completedRuns >= 8 && rng() < 0.05 ? 1 : 0),
        );
        const successCount = Math.max(0, completedRuns - failureCount);
        const medianDurationSec = jitter(rng, 180 + repoIndex * 70 + workflowOffset * 45, 60);
        const p90DurationSec = Math.round(medianDurationSec * (1.45 + rng() * 0.2));
        const values = {
          orgId: DEMO_ORG_SLUG,
          repoId,
          workflowId,
          day,
          successCount,
          failureCount,
          cancelledCount,
          medianDurationSec: String(medianDurationSec),
          p90DurationSec: String(p90DurationSec),
        };
        await db.insert(factWorkflowRunDaily).values(values).onConflictDoUpdate({
          target: [
            factWorkflowRunDaily.orgId,
            factWorkflowRunDaily.repoId,
            factWorkflowRunDaily.workflowId,
            factWorkflowRunDaily.day,
          ],
          set: values,
        });
      }
    }
  }
}

async function seedDemoCommitFacts(db: Database, repoIds: readonly bigint[], userIds: readonly bigint[]): Promise<void> {
  const rng = mulberry32(20260622);
  const days = daysSequence(addDays(todayUtc(), -DEMO_DAYS + 1), DEMO_DAYS);
  console.log('• demo: seeding commit aggregates');

  for (let dayIndex = 0; dayIndex < days.length; dayIndex += 1) {
    const day = days[dayIndex]!;
    const isWeekend = new Date(`${day}T00:00:00Z`).getUTCDay() % 6 === 0;
    const activeAuthors = Math.min(userIds.length, 5 + Math.round((dayIndex / Math.max(1, days.length - 1)) * 30));
    const pickedUsers = userIds.slice(0, activeAuthors);

    for (let repoIndex = 0; repoIndex < repoIds.length; repoIndex += 1) {
      const repoId = repoIds[repoIndex]!;
      const repoIntensity = [1.15, 1, 0.7, 0.85, 0.35][repoIndex] ?? 0.75;
      for (let authorIndex = 0; authorIndex < pickedUsers.length; authorIndex += 1) {
        const authorUserId = pickedUsers[authorIndex]!;
        const authorActivity = 0.25 + ((authorIndex % 7) / 10);
        const expected = repoIntensity * authorActivity * (isWeekend ? 0.25 : 1);
        const commitCount = Math.max(0, Math.round(expected + (rng() < expected % 1 ? 1 : 0) + (rng() < 0.08 ? 1 : 0)));
        if (commitCount === 0) continue;

        const additions = commitCount * jitter(rng, 70, 45);
        const deletions = Math.round(additions * (0.18 + rng() * 0.35));
        const values = {
          orgId: DEMO_ORG_SLUG,
          repoId,
          authorUserId,
          day,
          commitCount,
          additionsSum: BigInt(additions),
          deletionsSum: BigInt(deletions),
        };
        await db.insert(factCommitDaily).values(values).onConflictDoUpdate({
          target: [factCommitDaily.orgId, factCommitDaily.repoId, factCommitDaily.authorUserId, factCommitDaily.day],
          set: values,
        });
      }
    }
  }
}

