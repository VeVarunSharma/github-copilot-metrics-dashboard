function releaseRowsToEvents(
  rows: Array<typeof factReleaseDaily.$inferSelect>,
  releaseWindowDay?: string,
): ReleaseEvent[] {
  return rows.flatMap((row) => {
    const day = row.day;
    const latestTagAt = row.latestTagAt ?? dateAtUtc(day, 16, 0);
    return Array.from({ length: row.releaseCount }, (_, i) => {
      const isPrerelease = i < row.prereleaseCount;
      const tagAt =
        releaseWindowDay && day !== releaseWindowDay ?
          latestTagAt
        : new Date(latestTagAt.getTime() - Math.max(0, row.releaseCount - i - 1) * 45 * 60_000);
      return { day, isPrerelease, tagAt };
    });
  });
}

function commitRowsToEvents(rows: Array<typeof factCommitDaily.$inferSelect>): CommitEvent[] {
  return rows.flatMap((row) =>
    Array.from({ length: row.commitCount }, (_, i) => ({
      day: row.day,
      authoredAt: dateAtUtc(row.day, 8 + (i % 5), (Number(row.authorUserId % 53n) + i * 7) % 60),
    })),
  );
}

function workflowRowsToRuns(rows: Array<typeof factWorkflowRunDaily.$inferSelect>): WorkflowRun[] {
  return rows.flatMap((row) => {
    const runs: WorkflowRun[] = [];
    const durationSec = Number(row.medianDurationSec);
    const workflowId = Number(row.workflowId);
    const flakyCandidate = workflowId % 3 === 0 && row.successCount > 0;

    for (let i = 0; i < row.failureCount; i += 1) {
      const startedAt = dateAtUtc(row.day, flakyCandidate && i === 0 ? 9 : 16, i % 60);
      runs.push({
        workflowId,
        conclusion: 'failure',
        startedAt,
        completedAt: new Date(startedAt.getTime() + Math.round(durationSec * 1.15) * 1_000),
        attempt: 1,
      });
    }
    for (let i = 0; i < row.successCount; i += 1) {
      const startedAt = dateAtUtc(row.day, flakyCandidate ? 9 : 10, 20 + (i % 35));
      runs.push({
        workflowId,
        conclusion: 'success',
        startedAt,
        completedAt: new Date(startedAt.getTime() + durationSec * 1_000),
        attempt: flakyCandidate && i === 0 ? 2 : 1,
      });
    }
    for (let i = 0; i < row.cancelledCount; i += 1) {
      const startedAt = dateAtUtc(row.day, 12, i % 60);
      runs.push({
        workflowId,
        conclusion: 'cancelled',
        startedAt,
        completedAt: new Date(startedAt.getTime() + Math.round(durationSec * 0.4) * 1_000),
        attempt: 1,
      });
    }
    return runs;
  });
}

