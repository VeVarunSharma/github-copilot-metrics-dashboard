async function main(): Promise<void> {
  const opts = parseArgs(process.argv.slice(2));
  if (opts.help) {
    printHelp();
    return;
  }
  if (opts.reset && !opts.yes) {
    console.error('--reset is dangerous and requires --yes (or -y) to confirm.');
    process.exitCode = 1;
    return;
  }

  const url = process.env.DATABASE_URL;
  if (!url) throw new Error('DATABASE_URL is required to seed the database.');

  const db = createDb(url);

  if (opts.reset) {
    await resetAllFacts(db);
  }
  if (opts.clearDemo) {
    await clearDemoData(db);
  }

  await seedDimensions(db);
  await seedSettings(db);

  if (opts.demo) {
    await seedDemoOrg(db);
    const userIds = await seedDemoUsers(db, 35);
    const teamIds = await seedDemoTeams(db);
    const repoIds = await seedDemoRepos(db);
    await seedDemoFacts(db, userIds, teamIds);
    await seedDemoBilling(db);
    await seedDemoDeliveryFacts(db, repoIds, userIds);
    await rebuildGoldForOrg(db, DEMO_ORG_SLUG);
  }

  console.log('✅ seed complete');
}

await main();
process.exit(process.exitCode ?? 0);
